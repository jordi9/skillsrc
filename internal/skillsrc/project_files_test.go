func TestInitializeManifestCreatesMinimalManifestAndPreservesExisting(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	path := filepath.Join(root, "nested", "skills.toml")

	if err := InitializeManifest(path); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if got, want := string(data), "version = 1\n"; got != want {
		t.Fatalf("manifest = %q, want %q", got, want)
	}

	if err := InitializeManifest(path); err == nil {
		t.Fatal("InitializeManifest() overwrote an existing manifest")
	}
	after, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if string(after) != string(data) {
		t.Fatalf("existing manifest changed to %q", after)
	}
}

func TestInitializeManifestPublishesOnceUnderConcurrency(t *testing.T) {
	t.Parallel()
	path := filepath.Join(t.TempDir(), "skills.toml")
	start := make(chan struct{})
	results := make(chan error, 8)
	for range 8 {
		go func() {
			<-start
			results <- InitializeManifest(path)
		}()
	}
	close(start)
	succeeded := 0
	for range 8 {
		if err := <-results; err == nil {
			succeeded++
		}
	}
	if succeeded != 1 {
		t.Fatalf("successful initializers = %d, want 1", succeeded)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if got, want := string(data), "version = 1\n"; got != want {
		t.Fatalf("manifest = %q, want %q", got, want)
	}
}

func TestEnsureRootGitignorePreservesContentAndIsIdempotent(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	path := filepath.Join(root, ".gitignore")
	original := []byte("vendor/\n# keep this\n/.skillsrc-install.lock")
	if err := os.WriteFile(path, original, 0o644); err != nil {
		t.Fatal(err)
	}

	if err := EnsureRootGitignore(root); err != nil {
		t.Fatal(err)
	}
	want := "vendor/\n# keep this\n/.skillsrc-install.lock\n# skillsrc runtime\n/.agents/.gitignore\n"
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if got := string(data); got != want {
		t.Fatalf(".gitignore = %q, want %q", got, want)
	}
	if err := EnsureRootGitignore(root); err != nil {
		t.Fatal(err)
	}
	after, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if got := string(after); got != want {
		t.Fatalf("second .gitignore = %q, want %q", got, want)
	}
}

