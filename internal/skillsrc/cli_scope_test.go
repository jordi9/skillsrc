func TestCLIInitCreatesProjectFilesWithoutLock(t *testing.T) {
	home := t.TempDir()
	root := filepath.Join(home, "project")
	require.NoError(t, os.MkdirAll(root, 0o755))
	writeTestFile(t, filepath.Join(root, ".gitignore"), "keep/\n")
	var out, stderr bytes.Buffer
	runtime := scopeRuntime(root, home)
	runtime.Out, runtime.Err = &out, &stderr

	assert.Equal(t, 0, RunCLI(context.Background(), []string{"init"}, runtime), stderr.String())
	assert.Equal(t, "  ✓ "+filepath.Join("~", "project", "skills.toml")+" · initialized\n", out.String())
	manifest, err := os.ReadFile(filepath.Join(root, "skills.toml"))
	require.NoError(t, err)
	assert.Equal(t, "version = 1\n", string(manifest))
	assert.NoFileExists(t, filepath.Join(root, "skills.lock"))
	rootIgnore, err := os.ReadFile(filepath.Join(root, ".gitignore"))
	require.NoError(t, err)
	assert.Equal(t, "keep/\n# skillsrc runtime\n/.agents/.gitignore\n", string(rootIgnore))
	managed, err := os.ReadFile(filepath.Join(root, ".agents", ".gitignore"))
	require.NoError(t, err)
	assert.Equal(t, "# Generated by skillsrc. Do not edit.\n/skills/.skillsrc-*\n", string(managed))

	stderr.Reset()
	assert.Equal(t, 1, RunCLI(context.Background(), []string{"init"}, runtime))
	assert.Equal(t, "Error: project is already initialized at \"~/project/skills.toml\"\n", stderr.String())
}

func TestDisplayPathOnlyShortensPathsWithinHome(t *testing.T) {
	t.Parallel()
	home := filepath.Join(string(filepath.Separator), "Users", "person")
	assert.Equal(t, "~", displayPath(home, home))
	assert.Equal(t, filepath.Join("~", "project", "skills.toml"), displayPath(filepath.Join(home, "project", "skills.toml"), home))
	assert.Equal(t, filepath.Join(string(filepath.Separator), "opt", "project", "skills.toml"), displayPath(filepath.Join(string(filepath.Separator), "opt", "project", "skills.toml"), home))
}

func TestHumanPathDisplayShortensErrorsAndLocalSources(t *testing.T) {
	t.Parallel()
	home := filepath.Join(string(filepath.Separator), "Users", "person")
	path := filepath.Join(home, "project", "skills.toml")
	assert.Equal(t, `open "~/project/skills.toml": denied`, displayPathsInText(`open "`+path+`": denied`, home))
	assert.Equal(t, "~/project/skills.toml", displaySource(path, home))
	assert.Equal(t, "file://"+path, displayPathsInText("file://"+path, home))
}

