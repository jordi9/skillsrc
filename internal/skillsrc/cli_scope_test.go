func TestHelpUsesCommandOrientedLayout(t *testing.T) {
	t.Parallel()
	var output bytes.Buffer
	printUsage(&output)
	help := output.String()
	assert.Contains(t, help, "Usage: skillsrc [OPTIONS] <COMMAND>\n")
	assert.Contains(t, help, "Commands:\n  init      Initialize a manifest")
	assert.Contains(t, help, "Scope selection:\n")
	assert.Contains(t, help, "Options:\n")
	assert.NotContains(t, help, "[global flags]")
	assert.Equal(t, 1, strings.Count(help, "Usage:"))

	for _, flag := range []string{"-h", "--help"} {
		var stdout, stderr bytes.Buffer
		runtime := scopeRuntime(t.TempDir(), t.TempDir())
		runtime.Out, runtime.Err = &stdout, &stderr
		assert.Equal(t, 0, RunCLI(context.Background(), []string{flag}, runtime))
		assert.Contains(t, stdout.String(), "Commands:")
		assert.Empty(t, stderr.String())
	}
}

func TestCLIClassifiesCommandsBeforeDiscovery(t *testing.T) {
	home := t.TempDir()
	cwd := filepath.Join(home, "empty")
	require.NoError(t, os.MkdirAll(cwd, 0o755))
	var out, stderr bytes.Buffer
	runtime := scopeRuntime(cwd, home)
	runtime.Out, runtime.Err = &out, &stderr

	assert.Equal(t, 0, RunCLI(context.Background(), []string{"help"}, runtime))
	assert.NotContains(t, out.String(), "no project skills.toml")
	stderr.Reset()
	assert.Equal(t, 2, RunCLI(context.Background(), []string{"unknown"}, runtime))
	assert.NotContains(t, stderr.String(), "no project skills.toml")
	stderr.Reset()
	assert.Equal(t, 2, RunCLI(context.Background(), nil, runtime))
	assert.NotContains(t, stderr.String(), "no project skills.toml")
}

func TestCLIProjectDiscoveryDoesNotTreatUserManifestAsProject(t *testing.T) {
	home := t.TempDir()
	userRoot := filepath.Join(home, ".agents")
	cwd := filepath.Join(userRoot, "nested")
	local := filepath.Join(home, "source")
	require.NoError(t, os.MkdirAll(cwd, 0o755))
	makeSkill(t, filepath.Join(local, "one"), "one", "body")
	writeTestFile(t, filepath.Join(userRoot, "skills.toml"), "version = 1\n[[sources]]\npath = \"../source\"\nskills = [\"one\"]\n")
	var stderr bytes.Buffer
	runtime := scopeRuntime(cwd, home)
	runtime.Err = &stderr

	assert.Equal(t, 1, RunCLI(context.Background(), []string{"sync"}, runtime))
	assert.Contains(t, stderr.String(), "no project skills.toml found")
	assert.NoDirExists(t, filepath.Join(userRoot, ".agents"))

	stderr.Reset()
	assert.Equal(t, 0, RunCLI(context.Background(), []string{"-g", "sync"}, runtime), stderr.String())
	assert.FileExists(t, filepath.Join(userRoot, "skills", "one", "SKILL.md"))
	assert.NoDirExists(t, filepath.Join(userRoot, ".agents"))
}

func TestCLIProjectDiscoveryFromNestedDirectoryWritesManagedMetadata(t *testing.T) {
	home := t.TempDir()
	root := filepath.Join(home, "project")
	cwd := filepath.Join(root, "nested")
	local := filepath.Join(root, "source")
	require.NoError(t, os.MkdirAll(cwd, 0o755))
	makeSkill(t, filepath.Join(local, "one"), "one", "body")
	writeTestFile(t, filepath.Join(root, "skills.toml"), "version = 1\n[[sources]]\npath = \"./source\"\nskills = [\"one\"]\n")
	require.NoError(t, EnsureRootGitignore(root))
	var out, stderr bytes.Buffer
	runtime := scopeRuntime(cwd, home)
	runtime.Out, runtime.Err = &out, &stderr

	assert.Equal(t, 0, RunCLI(context.Background(), []string{"sync"}, runtime), stderr.String())
	assert.FileExists(t, filepath.Join(root, "skills.lock"))
	assert.FileExists(t, filepath.Join(root, ".agents", "skills", "one", "SKILL.md"))
	managed, err := os.ReadFile(filepath.Join(root, ".agents", ".gitignore"))
	require.NoError(t, err)
	assert.Contains(t, string(managed), "/skills/one/\n")
}

